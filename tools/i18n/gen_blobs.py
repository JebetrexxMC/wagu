#!/usr/bin/env python3
# 5.02.77: builds src/embed/i18n_blob.S + src/embed/i18n_blobs.h - the 20 language tables (assets/MP/lang/*.lng)
# and the neon menu letters (assets/MP/neon/intl/*.png + .txt) built into libMP (Android.mk: -I assets/MP).
import os, json
root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
langs = [L['code'] for L in json.load(open(os.path.join(root, 'tools', 'i18n', 'languages.json'), encoding='utf-8'))]
S = ['// 5.02.77: generated by tools/i18n/gen_blobs.py - the MP languages built into libMP', '    .section .rodata.mp_i18n,"a"']
H = ['// 5.02.77: generated by tools/i18n/gen_blobs.py', '#pragma once', '#include <cstddef>', 'extern "C" {']
rows = []
def blob(sym, path):
    S.extend(['    .balign 4', '    .global %s' % sym, '    .hidden %s' % sym, '%s:' % sym, '    .incbin "%s"' % path,
              '    .global %s_end' % sym, '    .hidden %s_end' % sym, '%s_end:' % sym, '    .byte 0'])
    H.append('    extern const unsigned char %s[], %s_end[];' % (sym, sym))
for i, c in enumerate(langs):
    blob('mp_lng_%d' % i, 'lang/%s.lng' % c)
    blob('mp_nip_%d' % i, 'neon/intl/%s.png' % c)
    blob('mp_nit_%d' % i, 'neon/intl/%s.txt' % c)
    rows.append('    { "%s", mp_lng_%d, mp_lng_%d_end, mp_nip_%d, mp_nip_%d_end, mp_nit_%d, mp_nit_%d_end },' % (c, i, i, i, i, i, i))
H.append('}')
H.append('struct MpLangBlob { const char* code; const unsigned char *lng, *lngEnd, *png, *pngEnd, *txt, *txtEnd; };')
H.append('static const MpLangBlob kMpLangBlobs[] = {'); H.extend(rows); H.append('};')
open(os.path.join(root, 'src', 'embed', 'i18n_blob.S'), 'w', newline='\n').write('\n'.join(S) + '\n')
open(os.path.join(root, 'src', 'embed', 'i18n_blobs.h'), 'w', newline='\n').write('\n'.join(H) + '\n')
print(len(langs), 'languages')
