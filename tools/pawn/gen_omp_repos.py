#!/usr/bin/env python3
# 5.02.05: third_party/omp-dev/repos.tsv (the open.mp / SA-MP development repositories wagu carries as submodules)
#   -> src/ui/omp_repos.h      (the launcher About page list: name, what it is, real address)
#   -> third_party/omp-dev/REPOS.md (the same list as tables)
# Run from the repo root: python3 tools/pawn/gen_omp_repos.py
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CATS = [('core', 'Core tools (compiler, stdlib, YSI)'), ('stdlib', 'Standard libraries'), ('sdk', 'SDKs and plugin frameworks'),
        ('includes', 'Pawn includes'), ('plugins', 'Server plugins'), ('crypto', 'Crypto and hashing'),
        ('langs', 'Other languages (C#, Go, JS, Java, Python, Lua, PHP, Kotlin)'), ('gamemodes', 'Gamemodes and scripts'),
        ('tools', 'Map, textdraw and animation tools'), ('editors', 'Editors'), ('web', 'Web tools and docs')]
CORE = [('compiler', 'Pawn compiler (pawncc)', 'https://github.com/ThirtyFoxMCx00E1/compiler'),
        ('omp-stdlib', 'open.mp standard includes', 'https://github.com/mpsamp-open/omp-stdlib'),
        ('qawno', 'open.mp Pawn editor', 'https://github.com/ThirtyFoxMCx00E1/qawno'),
        ('sampctl', 'package manager / build tool', 'https://github.com/mpsamp-open/sampctl'),
        ('sampctl2', 'package manager (second fork)', 'https://github.com/mpsamp-open/sampctl2'),
        ('YSI-Includes', 'YSI 5 libraries', 'https://github.com/ThirtyFoxMCx00E1/YSI-Includes'),
        ('amx_assembly', 'AMX assembly helpers', 'https://github.com/ThirtyFoxMCx00E1/amx_assembly'),
        ('code-parse.inc', 'pre-processor parsing', 'https://github.com/ThirtyFoxMCx00E1/code-parse.inc'),
        ('indirection', 'function pointers', 'https://github.com/ThirtyFoxMCx00E1/indirection'),
        ('md-sort', 'array sorting', 'https://github.com/ThirtyFoxMCx00E1/md-sort'),
        ('open.mp-gdk', 'server component SDK', 'https://github.com/ThirtyFoxMCx00E1/open.mp-gdk'),
        ('open.mp', 'open.mp server (crossplay)', 'https://github.com/openmultiplayer/open.mp')]
WEB = [('awesome open.mp', 'community list of libraries', 'https://open.mp/docs/awesome'),
       ('Pawn playground', 'compile Pawn in the browser', 'https://pg.open.mp/'),
       ('SA-MP model ids', 'object / model id search', 'https://dev.prineside.com/en/gtasa_samp_model_id/'),
       ('weather ids', 'weather id preview', 'https://dev.prineside.com/en/gtasa_weather_id/'),
       ('gang zone editor', 'draw gang zones on the map', 'https://dev.prineside.com/en/gtasa_gangzone_editor/')]

def clean(s, n=70):
    s = re.sub(r'[^\x20-\x7E]', '', s or '').strip()
    s = re.sub(r'\s+', ' ', s)
    return s if len(s) <= n else s[:n - 3].rstrip() + '...'

def esc(s): return s.replace('\\', '\\\\').replace('"', '\\"')

rows = []
for line in open(os.path.join(ROOT, 'third_party/omp-dev/repos.tsv'), encoding='utf-8'):
    if line.startswith('#') or not line.strip(): continue
    cat, repo, sha, br, up, desc = (line.rstrip('\n').split('\t') + [''] * 6)[:6]
    if repo.startswith('bitbucket:'):
        name, url = repo.split('/')[-1], 'https://bitbucket.org/' + repo[len('bitbucket:'):]
    else:
        name, url = repo.split('/')[1], 'https://github.com/' + repo
    what = clean(desc) or ('fork of ' + up if up else '')
    rows.append((cat, name, what, url, sha, up, 'third_party/omp-dev/%s/%s' % (cat, name.lstrip('.'))))

h = ['// 5.02.05: generated by tools/pawn/gen_omp_repos.py from third_party/omp-dev/repos.tsv - every open.mp / SA-MP',
     '// development repository wagu carries, with its real address. Shown on the launcher About page.',
     '#pragma once', 'struct OmpRepo { const char* cat; const char* name; const char* what; const char* url; };',
     'static const struct { const char* id; const char* title; } kOmpRepoCats[] = {']
h += ['    { "%s", "%s" },' % (c, esc(t)) for c, t in CATS]
h += ['};', 'static const OmpRepo kOmpRepos[] = {']
h += ['    { "core", "%s", "%s", "%s" },' % (n, esc(w), u) for n, w, u in CORE]
h += ['    { "%s", "%s", "%s", "%s" },' % (c, esc(n), esc(w), u) for c, n, w, u, *_ in rows]
h += ['    { "web", "%s", "%s", "%s" },' % (n, esc(w), u) for n, w, u in WEB]
h += ['};', 'static const int kOmpRepoCount = (int)(sizeof(kOmpRepos) / sizeof(kOmpRepos[0]));', '']
open(os.path.join(ROOT, 'src/ui/omp_repos.h'), 'w').write('\n'.join(h))

md = ['# open.mp / SA-MP development repositories', '',
      'Generated by `tools/pawn/gen_omp_repos.py` from `repos.tsv`. Every row is a git submodule pinned to the commit shown',
      '(nothing is downloaded by a normal clone). Fetch one: `git submodule update --init --depth 1 <folder>`.', '']
for cid, title in CATS:
    if cid in ('core', 'web'): continue
    sel = [r for r in rows if r[0] == cid]
    if not sel: continue
    md += ['## ' + title, '', '| Folder | Repository | Upstream | Commit | What it is |', '|---|---|---|---|---|']
    for c, n, w, u, sha, up, path in sel:
        upl = '[%s](https://github.com/%s)' % (up, up) if up else ''
        md.append('| `%s` | %s | %s | `%s` | %s |' % (path.split('omp-dev/')[1], u, upl, sha[:10], w.replace('|', '/')))
    md.append('')
md += ['## Web tools and docs', '']
md += ['- [%s](%s) - %s' % (n, u, w) for n, w, u in WEB]
md += ['', 'Extra files in `research/Samp/`: `Grimrandomer-samp-zone-editor-*.zip`, `Map Editor.zip`, `SHA512.zip`, `Tp/`,',
       '`YSI-Includes-nightly.zip`, `bmodshop.inc`, `nativechecker.zip`.', '']
open(os.path.join(ROOT, 'third_party/omp-dev/REPOS.md'), 'w').write('\n'.join(md))
print('%d repositories (+%d core, +%d web)' % (len(rows), len(CORE), len(WEB)))
